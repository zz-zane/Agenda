export function t(source, ...values) {
  const key = Array.isArray(source) ? source.reduce((s, part, i) => s + (i ? '{' + (i - 1) + '}' : '') + part, '') : source;
  const text = language === 'en' ? english[key] ?? key : key;
  return values.length ? text.replace(/\{(\d+)\}/g, (_, i) => String(values[Number(i)])) : text;
}
